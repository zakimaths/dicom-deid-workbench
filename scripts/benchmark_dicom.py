"""Read-only local corpus runner. No source names, values, mappings or outputs are published.

Manifest schema: {"schema":1,"split":"validation"|"test","cases":[
 {"id":"case-001","path":"relative/file.dcm","sha256":"..."}]}
Run only on synthetic or appropriately permitted datasets. This measures format and
metadata processing, NOT pixel-PHI detection or clinical anonymisation accuracy.
"""

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import time
import tracemalloc
from dicom_workbench.core import MAX_BYTES, Unsupported, transform


def run_manifest(manifest, root):
    if not isinstance(manifest, dict):
        raise ValueError("Manifest must be an object.")
    if manifest.get("schema") != 1 or manifest.get("split") not in ("validation", "test"):
        raise ValueError("Use manifest schema 1 and a validation or test split.")
    cases = manifest.get("cases")
    if not isinstance(cases, list) or not 1 <= len(cases) <= 10000:
        raise ValueError("List 1 to 10000 cases.")
    root = root.resolve()
    seen = set()
    results = []
    for case in cases:
        if not isinstance(case, dict):
            raise ValueError("Each manifest case must be an object.")
        # Output IDs are generated by the runner; no user-provided labels leave the process.
        candidate = case.get("path", "")
        digest = case.get("sha256", "")
        if not isinstance(candidate, str) or not re.fullmatch("[a-f0-9]{64}", digest):
            raise ValueError("Every case needs a relative path and SHA-256 hash.")
        path = (root / candidate).resolve()
        if Path(candidate).is_absolute() or not path.is_relative_to(root) or path in seen:
            raise ValueError("Paths must be unique and confined to the corpus folder.")
        seen.add(path)
        started = time.perf_counter()
        tracemalloc.start()
        try:
            with path.open("rb") as file:
                raw = file.read(MAX_BYTES + 1)
            if len(raw) > MAX_BYTES:
                status = "unsupported_size"
            elif sha256(raw).hexdigest() != digest:
                status = "integrity_failure"
            else:
                try:
                    result = transform(raw)
                    status = "accepted"
                    assert result.report["pixel_bytes_unchanged"]
                except Unsupported:
                    status = "rejected_by_contract"
        except OSError:
            status = "unavailable"
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        results.append(
            {
                "case": len(results) + 1,
                "status": status,
                "elapsed_ms": round((time.perf_counter() - started) * 1000),
                "peak_traced_python_bytes": peak,
            }
        )
    return {
        "schema": 1,
        "split": manifest["split"],
        "total": len(cases),
        "counts": {
            status: sum(r["status"] == status for r in results)
            for status in (
                "accepted",
                "rejected_by_contract",
                "unsupported_size",
                "integrity_failure",
                "unavailable",
            )
        },
        "pixel_phi_detection": "not_evaluated",
        "external_iod_validation": "not_performed",
        "cases": results,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.manifest.stat().st_size > 8 * 1024 * 1024:
            raise ValueError("Manifest too large.")
        report = run_manifest(json.loads(args.manifest.read_text()), args.root)
        with args.report.open("x") as file:
            json.dump(report, file, indent=2)
    except (OSError, ValueError, TypeError, KeyError):
        parser.exit(
            1, "Corpus run failed: check manifest, paths, permissions and a new report path.\n"
        )
    print(json.dumps(report["counts"]))


if __name__ == "__main__":
    main()
